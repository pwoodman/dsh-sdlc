/**
 * eval/lib/model-patch.mjs — pin the model for BOTH arms via a DSH patch layer.
 *
 * `dsh` has no `--model` launcher flag, and the headless app's only options are
 * `--json` and `--session-id`. The model is a composed-config value
 * (`agent-default-model`), so pinning it means generating a patch overlay and
 * passing it with `--patch`. The same overlay is passed to both arms, which is
 * what makes "the arms differ only in the composed profile" true by
 * construction rather than by assertion.
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

/**
 * Render a patch overlay that pins provider/model, or null when neither is set.
 * Quoting uses JSON string syntax, which is valid YAML double-quoted scalar.
 */
export function renderModelPatch({ provider = null, model = null } = {}) {
  if (!provider && !model) return null;
  const lines = [
    '# Generated by eval/run.mjs. Pins the model for EVERY arm so an observed',
    '# effect cannot be misattributed to a different snapshot.',
    '- id: agent-default-model',
    '  name: "@deepseek-ai/dsh-agent-default-model"',
    '  config:',
  ];
  if (provider) lines.push(`    provider: ${JSON.stringify(provider)}`);
  if (model) lines.push(`    model: ${JSON.stringify(model)}`);
  return `${lines.join('\n')}\n`;
}

/**
 * Write the patch overlay into `dir`.
 * @returns {{path:string, text:string}|null} null when nothing was pinned.
 */
export function writeModelPatch(dir, params = {}) {
  const text = renderModelPatch(params);
  if (!text) return null;
  mkdirSync(dir, { recursive: true });
  const path = join(dir, 'model-patch.yml');
  writeFileSync(path, text);
  return { path, text };
}

export default { renderModelPatch, writeModelPatch };
